//! Workspace automation for the slang Rust bindings.
//!
//! `cargo xtask codegen` regenerates every committed `generated/*.rs` file from
//! the vendored JSON models under `rust/model/`, which are themselves produced
//! by `scripts/syntax_gen.py --emit-model` and `scripts/diagnostic_gen.py
//! --emit-model`. `cargo xtask codegen --check` regenerates into memory and
//! fails if any committed file is stale.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use serde::Deserialize;

mod wasm_bridge;

const SLANG_VERSION: &str = "11.0";

#[derive(Deserialize)]
struct SyntaxModel {
    #[serde(rename = "modelHash")]
    model_hash: String,
    #[serde(rename = "syntaxKinds")]
    syntax_kinds: Vec<String>,
    #[serde(rename = "kindToStruct")]
    kind_to_struct: std::collections::BTreeMap<String, String>,
    #[serde(rename = "tokenKinds")]
    token_kinds: Vec<String>,
    #[serde(rename = "triviaKinds")]
    trivia_kinds: Vec<String>,
    structs: Vec<SyntaxStruct>,
}

#[derive(Deserialize)]
struct SyntaxStruct {
    name: String,
    base: String,
    #[serde(rename = "final")]
    is_final: bool,
    #[serde(default)]
    kinds: Vec<String>,
    #[serde(default)]
    members: Vec<SyntaxMember>,
}

#[derive(Deserialize)]
struct SyntaxMember {
    name: String,
    form: String,
    #[serde(rename = "type")]
    node_type: Option<String>,
    #[serde(default)]
    optional: bool,
    element: Option<String>,
}

#[derive(Deserialize)]
struct DiagModel {
    #[serde(rename = "modelHash")]
    model_hash: String,
    subsystems: Vec<DiagSubsystem>,
    groups: Vec<DiagGroup>,
}

#[derive(Deserialize)]
struct DiagSubsystem {
    name: String,
    diagnostics: Vec<DiagEntry>,
}

#[derive(Deserialize)]
struct DiagEntry {
    name: String,
    index: u16,
    severity: String,
    message: String,
    option: Option<String>,
}

#[derive(Deserialize)]
struct DiagGroup {
    name: String,
    options: Vec<String>,
}

#[derive(Deserialize)]
struct AstKindsModel {
    #[serde(rename = "modelHash")]
    model_hash: String,
    enums: std::collections::BTreeMap<String, AstEnum>,
}

#[derive(Deserialize)]
struct AstEnum {
    header: String,
    values: Vec<String>,
}

