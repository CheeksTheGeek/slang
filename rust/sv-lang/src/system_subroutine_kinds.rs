//! Small hand-written mirrors of two plain-C++-enum members of
//! `slang::ast::SystemSubroutine`: its `kind` (`slang::ast::SubroutineKind`)
//! and `knownNameId` (`slang::parsing::KnownSystemName`). Unlike the
//! syntax/diagnostic/symbol kind enumerations re-exported from
//! `sv_lang_kinds`, these are not part of that crate's generated-from-schema
//! pipeline; they mirror slang's C++ enums by hand because both are small
//! (`SubroutineKind`) or simply enumerate a fixed, rarely-changing list of
//! built-in name identifiers (`KnownSystemName`) read directly from
//! `slang/parsing/KnownSystemName.h`. Discriminants match the C++ enums
//! exactly, so they round-trip through the raw `u32` the C API exchanges.

/// Whether a [`SystemMethod`](crate::SystemMethod) (see
/// [`SystemMethod::kind`](crate::SystemMethod::kind)) is a task or a
/// function. Mirrors `slang::ast::SubroutineKind`.
#[repr(u32)]
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum SubroutineKind {
    /// A function: returns a value, callable from an expression context.
    Function = 0,
    /// A task: may consume simulation time, callable only as a statement.
    Task = 1,
}

impl SubroutineKind {
    /// Converts a raw discriminant from the native library, returning `None`
    /// for values outside the known range.
    #[inline]
    pub const fn from_raw(raw: u32) -> Option<Self> {
        match raw {
            0 => Some(Self::Function),
            1 => Some(Self::Task),
            _ => None,
        }
    }

    /// The raw discriminant.
    #[inline]
    pub const fn as_raw(self) -> u32 {
        self as u32
    }
}

impl core::fmt::Display for SubroutineKind {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str(match self {
            Self::Function => "function",
            Self::Task => "task",
        })
    }
}

